// Attachment feature tests: save-to-disk, typed content (PDF/ZIP/image/text),
// bulk fields, and is_latest/latest_only. Mirrors the acceptance tests from the
// clokio-mcp attachment spec (task #4809 shape), but against local fixtures so
// it needs no network or real key.
//
// Run by hand:  npm run build && node test/attachment-features.mjs

import { createServer } from 'node:http';
import { once } from 'node:events';
import { createHash, randomUUID } from 'node:crypto';
import { readFile, rm, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';

import { downloadAttachment, listZipEntries, stampIsLatest } from '../dist/attachments.js';

let fails = 0;
const check = (label, cond, extra = '') => {
  if (!cond) fails++;
  console.log(`${cond ? 'PASS' : 'FAIL'} ${label}${cond || !extra ? '' : `   (${extra})`}`);
};

// ---- Build fixtures: a valid PDF (via reportlab-free hand path won't parse, so
// we rely on a committed-at-runtime pdf generated by pdfjs's own expectations is
// hard; instead generate with the `zip` and a tiny real pdf from the system). ----
const fixDir = await mkdtemp(join(tmpdir(), 'clokio-mcp-fix-'));

// A real PDF: reportlab if present, else fall back to a known multi-page PDF
// shipped with macOS. The test asserts "parses to N pages with text", not exact
// bytes, so either source works.
let pdfBytes;
try {
  const py =
    'from reportlab.pdfgen import canvas;' +
    `c=canvas.Canvas(r'${join(fixDir, 'g.pdf')}');` +
    "c.drawString(72,700,'Popay test orders: hello');c.showPage();" +
    "c.drawString(72,700,'page two');c.showPage();c.save()";
  execFileSync('python3', ['-c', py], { stdio: 'ignore' });
  pdfBytes = await readFile(join(fixDir, 'g.pdf'));
} catch {
  pdfBytes = null; // reportlab missing - PDF assertions will be skipped with a note
}

// A real ZIP via the system `zip`.
writeFileSync(join(fixDir, 'a.txt'), 'hello one\n');
writeFileSync(join(fixDir, 'b.txt'), 'second file\n');
execFileSync('zip', ['-q', join(fixDir, 't.zip'), 'a.txt', 'b.txt'], { cwd: fixDir });
const zipBytes = await readFile(join(fixDir, 't.zip'));

// A tiny PNG (1x1).
const pngBytes = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==',
  'base64'
);
const csvBytes = Buffer.from('id,name\n1,alpha\n2,beta\n');

// ---- Mock API serving each fixture by attachment id ----
const byId = {
  10: { body: pdfBytes, type: 'application/pdf' },
  11: { body: zipBytes, type: 'application/zip' },
  12: { body: pngBytes, type: 'image/png' },
  13: { body: csvBytes, type: 'application/octet-stream' }, // API re-labels text as octet-stream
};
const api = createServer((req, res) => {
  const m = req.url.match(/\/attachments\/(\d+)$/);
  if (m && byId[m[1]]?.body) {
    res.writeHead(200, { 'content-type': byId[m[1]].type });
    return res.end(byId[m[1]].body);
  }
  res.writeHead(404, { 'content-type': 'application/json' });
  res.end(JSON.stringify({ status: 'error', message: 'not found' }));
});
api.listen(0, '127.0.0.1');
await once(api, 'listening');
const cfg = { baseUrl: `http://127.0.0.1:${api.address().port}`, apiKey: 'clk_test' };

// ---- 1. save_path writes the file; sha256 matches a direct hash ----
{
  const dest = join(fixDir, 'out', 'saved.zip');
  const r = await downloadAttachment(cfg, 1, 11, { fileName: 'archive.zip', savePath: dest });
  check('save_path returns saved_to', r.saved_to?.endsWith('saved.zip'), JSON.stringify(r));
  check('save_path reports file_size', r.file_size === zipBytes.byteLength);
  const onDisk = await readFile(dest);
  const want = createHash('sha256').update(zipBytes).digest('hex');
  check('saved bytes match source', Buffer.compare(onDisk, zipBytes) === 0);
  check('sha256 matches a direct hash of the bytes', r.sha256 === want, r.sha256);
}

// ---- 2. refuses to overwrite unless overwrite:true ----
{
  const dest = join(fixDir, 'dup.zip');
  await downloadAttachment(cfg, 1, 11, { fileName: 'a.zip', savePath: dest });
  let refused = false;
  try {
    await downloadAttachment(cfg, 1, 11, { fileName: 'a.zip', savePath: dest });
  } catch (e) {
    refused = /overwrite/i.test(e.message);
  }
  check('refuses to overwrite an existing file', refused);
  const ok = await downloadAttachment(cfg, 1, 11, {
    fileName: 'a.zip',
    savePath: dest,
    overwrite: true,
  });
  check('overwrite:true replaces it', ok.saved_to?.endsWith('dup.zip'));
}

// ---- 3. ZIP without save_path returns the entry list ----
{
  const r = await downloadAttachment(cfg, 1, 11, { fileName: 'archive.zip' });
  check('zip returns kind=zip', r.kind === 'zip', JSON.stringify(r).slice(0, 80));
  check('zip lists both entries', r.entry_count === 2, String(r.entry_count));
  const names = (r.entries ?? []).map((e) => e.name).sort();
  check('zip entry names are a.txt,b.txt', JSON.stringify(names) === '["a.txt","b.txt"]', JSON.stringify(names));
  check('zip entry carries a size', r.entries?.[0]?.size > 0);
}

// listZipEntries directly (pure function)
{
  const entries = listZipEntries(zipBytes);
  check('listZipEntries parses 2 entries', entries.length === 2);
}

// ---- 4. image without save_path comes back as image content ----
{
  const r = await downloadAttachment(cfg, 1, 12, { fileName: 'shot.png' });
  check('image returns __mcpContent', r?.__mcpContent === true, JSON.stringify(r).slice(0, 60));
  check('image block is type=image', r?.content?.[0]?.type === 'image');
  check('image block carries png mime', r?.content?.[0]?.mimeType === 'image/png');
  check('image data is base64 of the bytes', r?.content?.[0]?.data === pngBytes.toString('base64'));
}

// ---- 5. octet-stream CSV is recognised as text by extension ----
{
  const r = await downloadAttachment(cfg, 1, 13, { fileName: 'orders.csv' });
  check('csv (octet-stream) returns its text', typeof r === 'string' && r.includes('alpha'), String(r).slice(0, 40));
}

// ---- 6. PDF without save_path returns extracted text + page count ----
if (pdfBytes) {
  const r = await downloadAttachment(cfg, 1, 10, { fileName: 'summary.pdf' });
  check('pdf returns kind=pdf', r.kind === 'pdf', JSON.stringify(r).slice(0, 80));
  check('pdf reports 2 pages', r.pages === 2, String(r.pages));
  check('pdf text contains the drawn string', (r.text ?? '').includes('Popay test orders'), (r.text ?? '').slice(0, 50));
} else {
  console.log('SKIP pdf text (reportlab not installed to build a fixture)');
}

// ---- 7. is_latest / stampIsLatest ----
{
  const rows = [
    { id: 6534, file_name: 'one.pdf', created_at: '2026-10-01 10:00:00' },
    { id: 6535, file_name: 'two.zip', created_at: '2026-10-01 10:00:00' },
    { id: 6536, file_name: 'three.txt', created_at: '2026-10-01 10:00:00' },
    { id: 6530, file_name: 'one.pdf', created_at: '2026-09-30 09:00:00' }, // older dup of one.pdf
  ];
  const stamped = stampIsLatest(rows);
  const latest = stamped.filter((r) => r.is_latest).map((r) => r.id).sort((a, b) => a - b);
  check('is_latest keeps 3 current files (6534,6535,6536)', JSON.stringify(latest) === '[6534,6535,6536]', JSON.stringify(latest));
  check('the older duplicate 6530 is not latest', stamped.find((r) => r.id === 6530)?.is_latest === false);
  // id breaks a timestamp tie: a later-id upload with the same stamp wins.
  const tie = stampIsLatest([
    { id: 1, file_name: 'x', created_at: '2026-10-01 10:00:00' },
    { id: 2, file_name: 'x', created_at: '2026-10-01 10:00:00' },
  ]);
  check('id breaks a timestamp tie (higher id is latest)', tie.find((r) => r.id === 2)?.is_latest === true);
}

api.close();
await rm(fixDir, { recursive: true, force: true });

console.log(fails === 0 ? '\nAll attachment-feature tests passed.' : `\n${fails} FAILED`);
process.exit(fails ? 1 : 0);
